// Ilustrasi SVG sederhana: dipakai sebagai cadangan (thumbnail belum siap / WebGL tidak tersedia)
// dan sebagai muka depan kotak di 3D rak untuk perangkat yang modelnya bukan rackmount.
function svgLabel(fill, stroke, text, wide) {
  const [vw, vh] = wide ? [200, 36] : [200, 52];
  const w = wide ? 196 : 120;
  const h = wide ? 32 : 40;
  const x = (vw - w) / 2;
  const y = (vh - h) / 2;
  return `<svg viewBox="0 0 ${vw} ${vh}" xmlns="http://www.w3.org/2000/svg">
      <rect x="${x}" y="${y}" width="${w}" height="${h}" rx="3" fill="${fill}" stroke="${stroke}" stroke-width="1.2"/>
      <text x="${vw / 2}" y="${vh / 2 + 3}" text-anchor="middle" fill="${stroke}" font-size="9" font-family="monospace" font-weight="700">${text}</text>
    </svg>`;
}

const SHORT = {
  switch: "SWITCH",
  router: "ROUTER",
  firewall: "FIREWALL",
  ap: "AP",
  server: "SERVER",
  storage: "HDD",
  ups: "UPS",
  pdu: "PDU",
  nvr: "NVR",
  industri: "IND",
  monitor: "MONITOR",
  keyboard: "KEYBOARD",
  pc: "PC",
};

function build(rows, info, dir) {
  return rows.map(
    ([
      no,
      file,
      id,
      kind,
      U,
      watt,
      kg,
      [w, d, h],
      deskZone,
      rack,
      extraTags = [],
    ]) => {
      const k = KIND[kind];
      const m = info[no - 1];
      MODEL_OF[id] = { file: `${dir}/${file}`, rack };
      const unitNote = rack
        ? `${U}U rackmount.`
        : "Bukan rackmount, dihitung 1U untuk perencanaan.";
      return {
        id,
        kategori: k.kategori,
        nama: m.nama,
        merek: m.merek,
        unitHeight: U,
        tipe: k.tipe,
        beratKg: kg,
        watt,
        color: k.color,
        desc: `${m.fungsi} ${unitNote}`,
        tags: [...k.tags, ...extraTags],
        ilustrasi: svgLabel("#1a1d22", k.color, SHORT[kind], rack),
        dimCm: { w, d, h },
        deskZone,
        fromModel: true,
      };
    },
  );
}

